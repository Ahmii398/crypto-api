    w("\n**Year by year, net result (R)**\n")
    by_year = yearly.pivot(index="year", columns="preset", values="net_r").reindex(columns=names).reset_index().rename(columns={"year": "Year"})
    by_year["Year"] = by_year["Year"].astype(int).astype(str)
    w(table(by_year, {c: "{:+.1f}" for c in names}))
    w("")

    # ── 8 ──
    w("## 8. Statistical checks\n")
    w("**Bootstrap 95 % confidence interval of the expectancy (R per trade, after costs)**\n")
    part = boot[boot["period"].isin(["out_of_sample", "all"])][["preset", "period", "trades", "expectancy_r", "ci95_low", "ci95_high", "prob_expectancy_not_positive"]].copy()
    part.columns = ["Preset", "Period", "Trades", "Expectancy", "CI low", "CI high", "P(expectancy <= 0)"]
    w(table(part, {"Expectancy": "{:+.3f}", "CI low": "{:+.3f}", "CI high": "{:+.3f}", "P(expectancy <= 0)": "{:.2f}"}))
    w("\nThe \"all\" rows include the years the presets were selected on, so they are biased upwards; the out-of-sample rows are the honest ones.\n")
    w(f"**Random-entry baseline** ({int(rand['random_runs'].iloc[0])} runs per preset): the preset's own stop, target, direction, trend and session filters and trade frequency, but entries at random bars.\n")
    part = rand[rand["period"].isin(["out_of_sample"])][["preset", "trades", "expectancy_r", "random_expectancy_mean", "random_expectancy_p05", "random_expectancy_p95", "share_of_random_runs_beaten"]].copy()
    part.columns = ["Preset (out of sample)", "Trades", "Expectancy", "Random mean", "Random 5 %", "Random 95 %", "Random runs beaten"]
    w(table(part, {"Expectancy": "{:+.3f}", "Random mean": "{:+.3f}", "Random 5 %": "{:+.3f}", "Random 95 %": "{:+.3f}", "Random runs beaten": "{:.0%}"}))
    beat = rand[(rand["period"] == "out_of_sample") & (rand["share_of_random_runs_beaten"] >= 0.95)]["preset"].tolist()
    w("\nA preset whose entries carried information would beat about 95 % of the random runs. Out of sample " + (("only " + ", ".join(beat) + " does.") if beat else "none does.") + "\n")
    w("**Every eligible strategy, out of sample** (`results/eligible_out_of_sample.csv`)\n")
    rows = []
    for symbol in SYMBOLS:
        part = eligible[eligible["symbol"] == symbol]
        rows.append({"Asset": ASSET[symbol], "Eligible strategies": len(part), "Profitable out of sample": (part["oos_net_r"] > 0).mean(), "Median expectancy (R)": part["oos_expectancy_r"].median(), "Median before costs (R)": part["oos_gross_expectancy_r"].median(), "Median profit factor": part["oos_profit_factor"].median(), "Rank corr. selection score vs out-of-sample": part[["score", "oos_expectancy_r"]].corr(method="spearman").iloc[0, 1]})
