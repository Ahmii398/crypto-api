def build_workbook() -> None:
    df = search.load()
    df.to_csv(RESULTS_DIR / "optimization_results.csv.gz", index=False, float_format="%.5f", compression="gzip")
    usable = df[select._enough(df)].copy()
    usable["score_min_sharpe"] = np.minimum(usable["train_sharpe_monthly"], usable["val_sharpe_monthly"])
    top = usable.sort_values("score_min_sharpe", ascending=False).groupby(["symbol", "timeframe"], sort=False).head(100)
    sheets = {
        "Timeframes": _read("timeframe_comparison.csv"), "Modules": _read("module_comparison.csv"), "Parameter effects": _read("parameter_effects.csv"),
        "Top 100 per dataset": top, "Baseline + EMA grid": df[df["group"] != "random"], "Candidates": _read("candidates.csv"),
        "Preset performance": _read("final_performance.csv"), "Preset yearly": _read("final_yearly.csv"), "Preset regimes": _read("final_regimes.csv"),
        "Random baseline": _read("final_random_baseline.csv"), "Bootstrap": _read("final_bootstrap.csv"),
        "Eligible out of sample": _read("eligible_out_of_sample.csv"), "Walk-forward": _read("walk_forward.csv"),
    }  # fmt: skip
    tv = TV_DIR / "strategy_tester.csv"
    if tv.exists():
        sheets["TradingView"] = pd.read_csv(tv)
    with pd.ExcelWriter(RESULTS_DIR / "optimization_report.xlsx", engine="openpyxl") as writer:
        for name, frame in sheets.items():
            frame.replace([np.inf, -np.inf], np.nan).to_excel(writer, sheet_name=name[:31], index=False)


def main() -> None:
    (PROJECT_ROOT / "REPORT.md").write_text(build_report())
    build_workbook()
    print("wrote REPORT.md, results/optimization_report.xlsx, results/optimization_results.csv.gz")


if __name__ == "__main__":
    main()
