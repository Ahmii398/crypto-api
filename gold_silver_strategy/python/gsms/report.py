def table(df: pd.DataFrame, formats: dict | None = None) -> str:
    formats = formats or {}
    lines = ["| " + " | ".join(str(c) for c in df.columns) + " |", "|" + "|".join("---" for _ in df.columns) + "|"]
    for _, row in df.iterrows():
        cells = []
        for column in df.columns:
            value = row[column]
            if isinstance(value, (float, np.floating)) and not np.isfinite(value):
                cells.append("-")
            elif column in formats:
                cells.append(formats[column].format(value))
            else:
                cells.append(str(value))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _value(value) -> str:
    try:
        return f"{float(value):g}"
    except ValueError:
        return {"True": "on", "False": "off"}.get(str(value), str(value))


def _read(name: str) -> pd.DataFrame:
    return pd.read_csv(RESULTS_DIR / name)


def _preset_settings(presets: list[dict]) -> pd.DataFrame:
    rows = []
    for preset in presets:
        q = preset["params"]
        modules = [name for name, on in (("EMA", q["use_ema"]), ("Liquidity sweep", q["use_ls"]), ("Supply/demand", q["use_sd"]), ("Candles", q["use_cp"])) if on]
        patterns = [name for bit, name in ((1, "engulfing"), (2, "pin bar"), (4, "star"), (8, "piercing/dark cloud")) if q["cp_mask"] & bit]
        stop = {0: f"ATR x {q['sl_atr']:g}", 1: f"Structure, {q['sl_lookback']} bars + {q['sl_buffer']:g} ATR", 2: f"Zone + {q['sl_buffer']:g} ATR"}[q["sl_mode"]]
        rows.append({
            "Preset": preset["name"],
            "Modules": " + ".join(modules),
            "Confluence window": q["conf_window"],
            "EMA": f"{q['ema_fast']}/{q['ema_slow']} {LABELS['ema_mode'][q['ema_mode']]}" if q["use_ema"] else "-",
            "Liquidity sweep": f"swing {q['ls_swing']}, {LABELS['ls_source'][q['ls_source']]}, {LABELS['ls_mode'][q['ls_mode']]}" + (f" ({q['ls_reclaim']} bars)" if q["ls_mode"] == 1 else "") if q["use_ls"] else "-",
            "Supply/demand": f"swing {q['sd_swing']}, height {q['sd_width']:g} ATR, departure {q['sd_strength']:g} ATR, max touches {q['sd_max_touch']}, {LABELS['sd_inval'][q['sd_inval']]}, {LABELS['sd_confirm'][q['sd_confirm']]}, life {q['sd_max_age']}",
            "Candles": (", ".join(patterns) + (", strict" if q["cp_strict"] else ", relaxed") + (", confirmation candle" if q["cp_confirm"] else "")) if q["use_cp"] else "-",
            "Stop": stop,
            "Target (R)": f"{q['rr']:g}",
            "Trend EMA": q["trend_len"] or "off",
            "Session UTC": f"{q['sess_start']:02d}-{q['sess_end']:02d}" if q["sess_start"] >= 0 else "all",
        })  # fmt: skip
    return pd.DataFrame(rows)


def build_report() -> str:
    presets = json.loads((RESULTS_DIR / "final_configs.json").read_text())["presets"]
    perf, boot, rand = _read("final_performance.csv"), _read("final_bootstrap.csv"), _read("final_random_baseline.csv")
    tfc, eligible, wf, regimes, yearly = _read("timeframe_comparison.csv"), _read("eligible_out_of_sample.csv"), _read("walk_forward.csv"), _read("final_regimes.csv"), _read("final_yearly.csv")
    modules = _read("module_comparison.csv")
    df = search.load()
    quality = json.loads((RESULTS_DIR / "data_quality.json").read_text())

    std = perf[perf["cost_multiple"] == 1.0]
    oos = std[std["period"] == "out_of_sample"].set_index("preset")
    names = [p["name"] for p in presets]
    losers = [n for n in names if oos.loc[n, "net_r"] <= 0]
    winners = [n for n in names if oos.loc[n, "net_r"] > 0]
    gross = perf[(perf["cost_multiple"] == 0.0) & (perf["period"] == "out_of_sample")].set_index("preset")
    n_strategies, n_datasets = df["strategy_id"].nunique(), df.groupby(["symbol", "timeframe"]).ngroups
    out = []
    w = out.append
    ci_low = boot[boot["period"] == "out_of_sample"].set_index("preset")["ci95_low"]
    unproven = [n for n in winners if ci_low[n] <= 0]
    significance = "" if not winners else ", and the 95 % confidence interval of its expectancy still includes zero" if len(unproven) == len(winners) == 1 else f", and for {len(unproven)} of them the 95 % confidence interval of the expectancy includes zero"
    wf_total = wf.groupby(["symbol", "timeframe"])["chosen_test_net_r"].sum()

    w("# GSMS research report\n")
    w("Generated by `python -m gsms.report` from the files in `results/`. R = the amount risked on one trade; with 1 % of the account at risk, 1 R = 1 % of the account.\n")

    # ── 1 ──
    w("## 1. Bottom line\n")
    w(f"- **No configuration of this system has a statistically validated edge on gold or silver.** {n_strategies:,} parameter sets were tested on each of {n_datasets} symbol/timeframe datasets ({len(df):,} backtests) with realistic costs.")
    w(f"- The six presets were chosen on 2010-2021 data only. On the untouched 2022-2026 data **{len(losers)} of {len(names)} lost money** ({', '.join(losers)}); {('only ' + ', '.join(winners) + ' was profitable') if len(winners) == 1 else (', '.join(winners) + ' were profitable') if winners else 'none was profitable'}{significance} (section 8).")
    for symbol in SYMBOLS:
        part = eligible[eligible["symbol"] == symbol]
        w(f"- {ASSET[symbol]}: of all {len(part)} two-sided supply/demand strategies that were profitable in both 2010-2017 and 2018-2021, {(part['oos_net_r'] > 0).mean():.0%} were profitable in 2022-2026; median result {part['oos_expectancy_r'].median():+.3f} R per trade after costs, {part['oos_gross_expectancy_r'].median():+.3f} R before costs.")
    w(f"- Walk-forward (re-optimise on 4 years, trade the next year, {int(wf['test_year'].min())}-{int(wf['test_year'].max())}) lost money on {int((wf_total <= 0).sum())} of the {len(wf_total)} symbol/timeframe datasets" + (f"; the exceptions are {', '.join(f'{ASSET[s].split()[0]} {t} ({v:+.1f} R)' for (s, t), v in wf_total[wf_total > 0].items())}" if (wf_total > 0).any() else "") + " (section 8).")
    enough = tfc[tfc["strategies"] >= 100]
    slow = enough[enough["timeframe"].isin(["30m", "1h", "2h", "4h"])]
    cost = enough.pivot(index="timeframe", columns="symbol", values="median_cost_r_per_trade").dropna()
    ratio = (cost["XAGUSD"] / cost["XAUUSD"]).median()
    w(f"- Before costs the typical parameter set earns about 0 R per trade (median {enough['median_gross_expectancy_r'].min():+.3f} to {enough['median_gross_expectancy_r'].max():+.3f} R across datasets), and how a parameter set did before costs in 2010-2017 says almost nothing about 2018-2021: the rank correlation is {slow['train_validation_rank_corr_before_costs'].min():+.2f} to {slow['train_validation_rank_corr_before_costs'].max():+.2f} on 30m-4h. Costs then decide the result: the median cost per trade runs from {cost['XAUUSD'].min():.2f} R (gold, slowest timeframe) to {cost['XAGUSD'].max():.2f} R (silver, fastest), and is about {ratio:.1f} times larger on silver than on gold on the same timeframe (section 3).")
    tv_done = (TV_DIR / "NOTES.md").exists()
    w("- What is solid: the indicator and the strategy do what the rules say. The Pine scripts match the Python engine trade for trade in PineTS" + (" (section 10), and they compile and run in TradingView, where their trades agree with the Python engine up to the difference between price feeds (section 11)." if tv_done else " (section 10); TradingView results are not recorded yet."))
    w("- Practical reading: use the indicator as a chart-reading aid (zones, sweeps, patterns, alerts). Do not expect the presets to be profitable; the evidence says they are not.\n")

    # ── 2 ──
    w("## 2. What was tested\n")
    w("| | |\n|---|---|")
    for symbol in SYMBOLS:
        q = quality[symbol]
        spread = q["spread"]["overall"]
        w(f"| {ASSET[symbol]} data | 1-minute bid bars, HistData 2009-2026 (Dukascopy for Feb-Jul 2023), checked against Dukascopy and an independent daily series; see `results/data_quality.md` |")
        w(f"| {ASSET[symbol]} cost | {backtest.COST_PCT_PER_SIDE[symbol]:g} % of traded value per fill; measured median quoted spread {spread['bp_median_all_hours']:.1f} bp ({spread['bp_median_since_2022']:.1f} bp since 2022) |")
    w(f"| Timeframes | {', '.join(TIMEFRAMES)}; bars aligned to the 18:00 New York session like TradingView's metal charts |")
    w(f"| Train | {search.TRAIN[0]} to {search.TRAIN[1]} (exclusive) |")
    w(f"| Validation | {search.VALIDATION[0]} to {search.VALIDATION[1]} |")
    w(f"| Out of sample | {search.OOS[0]} to {search.OOS[1]}; simulated only after the presets were fixed (see the git history) |")
    w(f"| Strategies | {int((df['group'] == 'baseline').sum() / n_datasets)} module combinations at default settings, {int((df['group'] == 'ema_grid').sum() / n_datasets)} EMA grid points, {int((df['group'] == 'random').sum() / n_datasets):,} random draws from the parameter space in `python/gsms/space.py` |")
    w(f"| Selection rules | supply/demand on, two-sided, at least {select.MIN_TRAIN_TRADES} train and {select.MIN_VAL_TRADES} validation trades, profitable in both periods, at least {select.MIN_NEIGHBOUR_SHARE:.0%} of one-step neighbours profitable; ranked by min(train, validation) monthly Sharpe |")
    w("")

    # ── 3 ──
    w("## 3. Timeframe comparison (train and validation data only)\n")
    w(f"Random parameter sets with at least {select.MIN_TRAIN_TRADES}/{select.MIN_VAL_TRADES} train/validation trades. \"Both\" = profitable after costs in the train period and in the validation period.\n")
    for symbol in SYMBOLS:
        part = tfc[tfc["symbol"] == symbol][["timeframe", "strategies", "median_trades_per_year", "median_cost_r_per_trade", "median_gross_expectancy_r", "median_net_expectancy_r", "share_profitable_both", "train_validation_rank_corr", "train_validation_rank_corr_before_costs", "top10pct_train_share_profitable_validation"]]
        part.columns = ["Timeframe", "Sets with enough trades", "Median trades/yr", "Cost per trade (R)", "Expectancy before costs (R)", "Expectancy after costs (R)", "Profitable in both", "Train-validation rank corr.", "Same, before costs", "Top 10 % of train: profitable in validation"]
        w(f"**{ASSET[symbol]}**\n")
        w(table(part, {"Median trades/yr": "{:.0f}", "Cost per trade (R)": "{:.3f}", "Expectancy before costs (R)": "{:+.3f}", "Expectancy after costs (R)": "{:+.3f}", "Profitable in both": "{:.1%}", "Train-validation rank corr.": "{:+.2f}", "Same, before costs": "{:+.2f}", "Top 10 % of train: profitable in validation": "{:.0%}"}))
        w("")
        if len(part):
            ok = part[part["Sets with enough trades"] >= 100]
            best = ok.sort_values("Profitable in both", ascending=False).iloc[0]
            oos_tf = eligible[eligible["symbol"] == symbol].groupby("timeframe").agg(n=("oos_net_r", "size"), share=("oos_net_r", lambda x: (x > 0).mean()))
            line = ", ".join(f"{tf} {int(r.n)} sets / {r.share:.0%}" for tf, r in oos_tf.reindex([t for t in TIMEFRAMES if t in oos_tf.index]).iterrows())
            w(f"Most consistent timeframe for {ASSET[symbol]} before the out-of-sample test: **{best['Timeframe']}** ({best['Profitable in both']:.1%} of sets profitable in both periods, lowest cost per trade among the timeframes with enough trades). Out of sample, the share of eligible sets that stayed profitable was: {line}.\n")
    w("The rank correlation after costs is high on the short timeframes, but the same correlation before costs is close to zero. So it is not persistent skill: a parameter set that trades often with tight stops pays the same costs in both periods.\n")

    # ── 4 ──
    w("## 4. Strategy combinations\n")
    w("Share of random parameter sets that were profitable after costs in both train and validation, by module combination (all 15) and timeframe. Cells with fewer than 20 sets show a dash. Full table including the default-setting results: `results/module_comparison.csv`.\n")
    for symbol in SYMBOLS:
        part = modules[(modules["symbol"] == symbol) & (modules["strategies"] >= 20)]
        pivot = part.pivot(index="modules", columns="timeframe", values="share_profitable_both").reindex(columns=[t for t in TIMEFRAMES if t in part["timeframe"].unique()])
        order = sorted(pivot.index, key=lambda m: (m.count("+"), m))
        pivot = pivot.reindex(order).reset_index().rename(columns={"modules": "Modules"})
        w(f"**{ASSET[symbol]}**\n")
        w(table(pivot, {c: "{:.0%}" for c in pivot.columns if c != "Modules"}))
        w("")

    # ── 5 ──
    effects = _read("parameter_effects.csv")
    w("## 5. Parameter effects\n")
    w("Median validation expectancy (R per trade, after costs) and share profitable in both periods by setting value, all timeframes pooled. Differences are small next to the cost drag. Everything is in `results/parameter_effects.csv`.\n")
    label = {"ema_fast": "Fast EMA", "ema_slow": "Slow EMA", "rr": "Target (R multiple)", "sl_mode": "Stop method (0 ATR, 1 structure, 2 zone)", "sd_max_touch": "Zone touches traded (1 = fresh only)", "sd_confirm": "Zone entry (0 touch, 1 rejection close)", "ls_mode": "Sweep confirmation (0 wick, 1 close)", "ls_source": "Liquidity levels (0 swings ... 3 PDH/PDL, 4 PDH/PDL+PWH/PWL)", "cp_strict": "Strict candle rules", "cp_confirm": "Confirmation candle", "direction": "Direction (0 both, 1 long, 2 short)"}
    for symbol in SYMBOLS:
        w(f"**{ASSET[symbol]}**\n")
        rows = []
        for setting, text in label.items():
            part = effects[(effects["symbol"] == symbol) & (effects["setting"] == setting)]
            rows.append({"Setting": text, "Value: median validation expectancy / share profitable in both": "; ".join(f"{_value(v)}: {e:+.2f} / {b:.0%}" for v, e, b in zip(part["value"], part["median_validation_expectancy_r"], part["share_profitable_both"]))})
        w(table(pd.DataFrame(rows)))
        w("")

    # ── 6 ──
    w("## 6. Final configurations\n")
    w("Chosen from train and validation data. They are compiled into both Pine scripts as presets; exact values are in `results/final_configs.json`.\n")
    w(table(_preset_settings(presets)))
    w("")

    # ── 7 ──
    w("## 7. Performance of the presets\n")
    cols = ["preset", "period", "trades", "win_rate", "profit_factor", "expectancy_r", "net_r", "max_dd_r", "payoff", "avg_win_r", "avg_loss_r", "max_consec_wins", "max_consec_losses", "trades_per_year", "sharpe_monthly"]
    part = std[std["period"].isin(["train", "validation", "out_of_sample"])][cols].copy()
    part.columns = ["Preset", "Period", "Trades", "Win rate", "Profit factor", "Expectancy (R)", "Net (R)", "Max DD (R)", "Avg win / avg loss", "Avg win (R)", "Avg loss (R)", "Max wins in a row", "Max losses in a row", "Trades/yr", "Monthly Sharpe"]
    w(table(part, {"Win rate": "{:.1%}", "Profit factor": "{:.2f}", "Expectancy (R)": "{:+.3f}", "Net (R)": "{:+.1f}", "Max DD (R)": "{:.1f}", "Avg win / avg loss": "{:.2f}", "Avg win (R)": "{:.2f}", "Avg loss (R)": "{:.2f}", "Trades/yr": "{:.0f}", "Monthly Sharpe": "{:+.2f}"}))
    w("\nWith $100 at risk per trade on a $10,000 account (1 %), net profit in dollars = Net (R) x 100 and max drawdown in dollars = Max DD (R) x 100, not compounded.\n")
    w("**Long and short, out of sample**\n")
    part = std[std["period"] == "out_of_sample"][["preset", "long_trades", "long_win_rate", "long_net_r", "short_trades", "short_win_rate", "short_net_r"]].copy()
    part.columns = ["Preset", "Long trades", "Long win rate", "Long net (R)", "Short trades", "Short win rate", "Short net (R)"]
    w(table(part, {"Long win rate": "{:.1%}", "Long net (R)": "{:+.1f}", "Short win rate": "{:.1%}", "Short net (R)": "{:+.1f}"}))
    w("\n**Cost sensitivity, out of sample net result (R)**\n")
    sens = perf[perf["period"] == "out_of_sample"].pivot(index="preset", columns="cost_multiple", values="net_r").reindex(names).reset_index()
    sens.columns = ["Preset", "No costs", "Half costs", "Modelled costs", "Double costs"]
