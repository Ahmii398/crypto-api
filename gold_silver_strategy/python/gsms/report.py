    w(f"\n**Walk-forward**: every year from {int(wf['test_year'].min())} to {int(wf['test_year'].max())}, the supply/demand strategy with the best monthly Sharpe over the previous {int(wf['test_year'].iloc[0] - wf['fit_from'].iloc[0])} years (at least 60 trades, profitable) is traded for that year.\n")
    summary = wf.groupby(["symbol", "timeframe"], sort=False).agg(years=("test_year", "size"), chosen=("chosen_test_net_r", "sum"), good=("chosen_test_net_r", lambda x: int((x > 0).sum())), top10=("top10_test_net_r_mean", "sum"), pool=("pool_test_net_r_median", "sum"), share=("pool_share_profitable_in_test", "mean")).reset_index()
    summary.columns = ["Symbol", "Timeframe", "Test years", "Chosen strategy, total (R)", "Profitable years", "Average of top 10, total (R)", "Median strategy in pool, total (R)", "Pool profitable in a test year"]
    w(table(summary, {"Chosen strategy, total (R)": "{:+.1f}", "Average of top 10, total (R)": "{:+.1f}", "Median strategy in pool, total (R)": "{:+.1f}", "Pool profitable in a test year": "{:.0%}"}))
    w("")

    # ── regimes ──
    w("## 9. Market conditions\n")
    w("Expectancy (R per trade after costs) and number of trades by the condition of the session in which the trade was opened, whole history 2010-2026. Definitions are in `python/gsms/regimes.py`: trend and volatility use earlier sessions only; \"NFP\" is the first Friday of the month; \"release shock\" is a data-defined proxy for major scheduled news; \"reversal\" marks sessions that made a new 10-day extreme and closed back through the previous close. Out-of-sample-only figures are in `results/final_regimes.csv`.\n")
    part = regimes[regimes["scope"] == "all"].copy()
    part["cell"] = part.apply(lambda r: f"{r['expectancy_r']:+.2f} ({int(r['trades'])})", axis=1)
    naming = {("trend", "bull"): "Bull trend", ("trend", "bear"): "Bear trend", ("trend", "sideways"): "Sideways", ("volatility", "high"): "High volatility", ("volatility", "normal"): "Normal volatility", ("volatility", "low"): "Low volatility", ("nfp", "True"): "NFP day", ("shock", "True"): "Release shock", ("shock", "False"): "No release shock", ("reversal", "True"): "Reversal day"}
    part["Condition"] = [naming.get((r, v)) for r, v in zip(part["regime"], part["value"])]
    pivot = part.dropna(subset=["Condition"]).pivot(index="Condition", columns="preset", values="cell").reindex(index=list(naming.values()), columns=names).fillna("-").reset_index()
    w(table(pivot))
    signs = part.dropna(subset=["Condition"]).groupby("Condition")["expectancy_r"].agg(lambda x: f"{int((x > 0).sum())} of {len(x)}")
    w("\nPresets with a positive expectancy in each condition (whole history, which includes the years they were fitted on): " + "; ".join(f"{name} {signs[name]}" for name in naming.values() if name in signs.index) + ".\n")

    # ── verification ──
    w("## 10. Is the code doing what the rules say?\n")
    w("| Check | Result |\n|---|---|")
    for target, text in (("strategy", "Strategy script, random settings over all 15 module combinations and 7 timeframes"), ("indicator", "Indicator script (the trade ledger behind its dashboard), same kind of runs"), ("presets_strategy", "Strategy script as shipped, each preset on its own symbol and timeframe"), ("presets_indicator", "Indicator script as shipped, each preset")):
        path = RESULTS_DIR / f"parity_pinets_{target}.json"
        if path.exists():
            runs = json.loads(path.read_text())
            w(f"| PineTS parity: {text} | {sum(r['exact'] for r in runs)} of {len(runs)} runs identical to the Python engine on every bar and every trade ({sum(r['trades']['python'] for r in runs):,} trades) |")
    w("| Engine unit tests (`python/tests`) | fill rules on hand-made bars (next-open entry, gaps, stop and target in one bar, costs) and a no-look-ahead test: results up to any bar do not change when later bars are added |")
    w("| TradingView | both scripts compile and run; trade lists agree with the Python engine up to the difference between the two price feeds (section 11) |" if (TV_DIR / "NOTES.md").exists() else "| TradingView | not recorded yet |")
    w("\nPineTS is an open-source Pine Script runtime. It runs the generated Pine source bar by bar on the research data, which is what makes an exact comparison possible; it is not TradingView.\n")

